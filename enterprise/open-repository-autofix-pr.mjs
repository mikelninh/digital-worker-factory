#!/usr/bin/env node
import fs from 'node:fs'
import path from 'node:path'
import { runRepositoryAutofixLoop } from './repo-security-orchestrator.mjs'

const token = process.env.GITHUB_TOKEN
const repository = process.env.GITHUB_REPOSITORY
const baseBranch = process.env.TRUSTREADY_BASE_BRANCH || 'main'
const targetArg = process.argv[2]

if (!targetArg) {
  console.error('usage: node enterprise/open-repository-autofix-pr.mjs <repository-root>')
  process.exit(2)
}
if (!token || !repository) {
  console.error('GITHUB_TOKEN and GITHUB_REPOSITORY are required')
  process.exit(2)
}

const [owner, repo] = repository.split('/')
if (!owner || !repo) throw new Error('invalid_GITHUB_REPOSITORY')

const targetRoot = path.resolve(targetArg)
const report = await runRepositoryAutofixLoop(targetRoot)
if (report.release?.decision !== 'TECHNICAL_GO' || report.pr?.ready !== true) {
  console.error(`Autofix PR blocked: ${report.release?.decision ?? 'unknown'} / ${report.release?.reason ?? 'unknown'}`)
  process.exit(3)
}

const headers = {
  Accept: 'application/vnd.github+json',
  Authorization: `Bearer ${token}`,
  'X-GitHub-Api-Version': '2022-11-28',
  'Content-Type': 'application/json',
}

async function gh(method, endpoint, body = undefined) {
  const response = await fetch(`https://api.github.com/repos/${owner}/${repo}${endpoint}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  })
  const text = await response.text()
  let payload = null
  try { payload = text ? JSON.parse(text) : null } catch { payload = { raw: text } }
  if (!response.ok) {
    const error = new Error(`github_api_${response.status}:${method}:${endpoint}`)
    error.payload = payload
    throw error
  }
  return payload
}

const baseRef = await gh('GET', `/git/ref/heads/${encodeURIComponent(baseBranch)}`)
const baseSha = baseRef.object.sha
const suffix = process.env.GITHUB_RUN_ID || String(Date.now())
const branch = `trustready/security-autofix-${suffix}`

await gh('POST', '/git/refs', { ref: `refs/heads/${branch}`, sha: baseSha })

for (const file of report.pr.files) {
  const relativeFromRepo = path.relative(process.cwd(), path.join(targetRoot, file.path)).replaceAll('\\', '/')
  if (relativeFromRepo.startsWith('../')) throw new Error(`target_file_outside_repository:${file.path}`)
  const current = await gh('GET', `/contents/${relativeFromRepo}?ref=${encodeURIComponent(baseBranch)}`)
  await gh('PUT', `/contents/${relativeFromRepo}`, {
    message: `TrustReady: enforce deterministic boundary in ${file.path}`,
    content: Buffer.from(file.content, 'utf8').toString('base64'),
    sha: current.sha,
    branch,
  })
}

const beforeEscapes = report.runtimeBefore?.impactEscapes
const beforeCalls = report.runtimeBefore?.executorCalls
const afterEscapes = report.runtimeAfter?.impactEscapes
const afterCalls = report.runtimeAfter?.executorCalls
const body = [
  'Generated by TrustReady Repo-to-PR Security v2 after an isolated attack → patch → retest loop.',
  '',
  '### Evidence',
  `- Runtime impact escapes: **${beforeEscapes} → ${afterEscapes}**`,
  `- Executor calls: **${beforeCalls} → ${afterCalls}**`,
  `- Release decision after patch: **${report.release.decision}**`,
  `- Patch reason: \`${report.patch.reason}\``,
  '',
  '### Safety boundary',
  '- This PR was created only after the same runtime attack set produced zero post-patch executor impact.',
  '- It is intentionally **not auto-merged**. Repository owners retain review, merge and deployment authority.',
  '- TECHNICAL_GO covers the supported discovered runtime shape and generated attack set; it is not certification or a guarantee that all vulnerabilities were found.',
].join('\n')

const pull = await gh('POST', '/pulls', {
  title: report.pr.title,
  head: branch,
  base: baseBranch,
  body,
  maintainer_can_modify: true,
})

const output = {
  version: 'repository-autofix-pr/v1',
  repository,
  baseBranch,
  branch,
  pullNumber: pull.number,
  pullUrl: pull.html_url,
  files: report.pr.files.map((file) => file.path),
  runtimeBefore: { impactEscapes: beforeEscapes, executorCalls: beforeCalls },
  runtimeAfter: { impactEscapes: afterEscapes, executorCalls: afterCalls },
  release: report.release,
  autoMerged: false,
}

const outputPath = process.env.TRUSTREADY_PR_RECEIPT || path.join(process.cwd(), 'enterprise', 'repo-autofix-pr-receipt.json')
fs.writeFileSync(outputPath, `${JSON.stringify(output, null, 2)}\n`)
if (process.env.GITHUB_OUTPUT) {
  fs.appendFileSync(process.env.GITHUB_OUTPUT, `pull_url=${pull.html_url}\npull_number=${pull.number}\nbranch=${branch}\n`)
}
console.log(`TRUSTREADY_AUTOFIX_PR=${JSON.stringify(output)}`)
